"""Run the first sequential rate--interest--inflation feedback experiment.

The experiment starts from the warmed 2026Q4 Treasury stock.  A 500-basis-point
Treasury premium lasts ten years, while later Federal Reserve rate changes are
generated by the policy rule.  Debt stabilization and terminal inflation are
never supplied as targets.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

import pandas as pd

from debt_sim.crisis import (
    InterestIncomeRule,
    PrivateAbsorptionRule,
    SequentialFeedbackRule,
    build_private_absorption_diagnostics,
    run_sequential_crisis_simulation,
    summarize_crisis_path,
    summarize_private_absorption,
)
from debt_sim.data import load_baseline_bundle
from debt_sim.policy import PolicyRegime, PolicyRule
from debt_sim.scenarios import build_baseline_scenario, prepare_starting_state

START = pd.Period("2026Q4", freq="Q")
END = pd.Period("2056Q3", freq="Q")
PREMIUM_BASIS_POINTS = 500.0
PREMIUM_QUARTERS = 40
PRIVATE_CREDIT_SPREAD_BASIS_POINTS = 200.0
PRIVATE_CREDIT_SPREAD_QUARTERS = 8
INFLATION_CEILINGS = (0.03, 0.04, 0.06, 0.08)
SUSTAINED_BREACH_QUARTERS = 4
OUTPUT_DIR = Path("data/processed")
CONFIG_DIR = Path("config/scenarios")
HOLDER_CALIBRATION_PATH = Path("config/calibration/interest_recipient_shares_2026.json")


def _interest_rule(
    domestic_spending_fraction: float,
    foreign_spending_fraction: float,
    holder_shares: dict[str, float],
):
    return InterestIncomeRule(
        domestic_private_share=holder_shares["domestic_private_share"],
        foreign_share=holder_shares["foreign_share"],
        federal_reserve_share=holder_shares["federal_reserve_share"],
        domestic_private_spending_fraction=domestic_spending_fraction,
        foreign_domestic_spending_fraction=foreign_spending_fraction,
        federal_reserve_spending_fraction=0.0,
    )


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    bundle = load_baseline_bundle()
    holder_calibration = json.loads(HOLDER_CALIBRATION_PATH.read_text())
    holder_shares = {
        key: float(holder_calibration[key])
        for key in ("domestic_private_share", "foreign_share", "federal_reserve_share")
    }
    starting = prepare_starting_state(bundle, START)
    reference = build_baseline_scenario(
        bundle,
        start_period=START,
        end_period=END,
    ).quarterly_assumptions
    premium = pd.Series(0.0, index=reference.index)
    premium.iloc[:PREMIUM_QUARTERS] = PREMIUM_BASIS_POINTS
    no_private_spread = pd.Series(0.0, index=reference.index)
    private_spread = no_private_spread.copy()
    private_spread.iloc[:PRIVATE_CREDIT_SPREAD_QUARTERS] = PRIVATE_CREDIT_SPREAD_BASIS_POINTS

    policy_rule = PolicyRule(regime=PolicyRegime.PRICE_STABILITY)
    feedback_rule = SequentialFeedbackRule()
    scenarios = {
        "no_shock_central_spending": {
            "premium": pd.Series(0.0, index=reference.index),
            "private_spread": no_private_spread,
            "income": _interest_rule(0.25, 0.05, holder_shares),
        },
        "stress_no_interest_spending": {
            "premium": premium,
            "private_spread": private_spread,
            "income": _interest_rule(0.0, 0.0, holder_shares),
        },
        "stress_central_spending_no_private_spread": {
            "premium": premium,
            "private_spread": no_private_spread,
            "income": _interest_rule(0.25, 0.05, holder_shares),
        },
        "stress_central_interest_spending": {
            "premium": premium,
            "private_spread": private_spread,
            "income": _interest_rule(0.25, 0.05, holder_shares),
        },
        "stress_high_interest_spending": {
            "premium": premium,
            "private_spread": private_spread,
            "income": _interest_rule(0.50, 0.10, holder_shares),
        },
        "stress_full_domestic_interest_spending": {
            "premium": premium,
            "private_spread": private_spread,
            "income": _interest_rule(1.0, 0.10, holder_shares),
        },
    }

    results = {}
    for name, parameters in scenarios.items():
        results[name] = run_sequential_crisis_simulation(
            starting.stock,
            reference,
            initial_nominal_gdp_billions_saar=starting.initial_nominal_gdp_billions_saar,
            initial_real_gdp_billions_chained_saar=(
                starting.initial_real_gdp_billions_chained_saar
            ),
            policy_rule=policy_rule,
            feedback_rule=feedback_rule,
            interest_income_rule=parameters["income"],
            treasury_premium_basis_points=parameters["premium"],
            private_credit_spread_basis_points=parameters["private_spread"],
            issuance_strategy=bundle.issuance_strategy,
            scenario_name=name,
            data_vintage=bundle.cbo_vintage,
        )

    paths = pd.concat(
        [result.quarterly.assign(scenario=name) for name, result in results.items()],
        ignore_index=True,
    )
    paths.to_csv(OUTPUT_DIR / "sequential_crisis_2026_paths.csv", index=False)

    four_percent_summary = pd.DataFrame(
        [
            summarize_crisis_path(
                result,
                inflation_ceiling=0.04,
                sustained_quarters=SUSTAINED_BREACH_QUARTERS,
            )
            for result in results.values()
        ]
    )
    four_percent_summary.to_csv(
        OUTPUT_DIR / "sequential_crisis_2026_summary.csv",
        index=False,
    )
    inflation_frontier = pd.DataFrame(
        [
            summarize_crisis_path(
                result,
                inflation_ceiling=ceiling,
                sustained_quarters=SUSTAINED_BREACH_QUARTERS,
            )
            for result in results.values()
            for ceiling in INFLATION_CEILINGS
        ]
    )
    inflation_frontier.to_csv(
        OUTPUT_DIR / "sequential_crisis_2026_inflation_frontier.csv",
        index=False,
    )

    absorption_rules = {
        "tight_capacity": PrivateAbsorptionRule(
            capacity_increase_fraction_per_100_basis_points=0.025,
            maximum_capacity_multiple=1.25,
        ),
        "central_capacity": PrivateAbsorptionRule(
            capacity_increase_fraction_per_100_basis_points=0.05,
            maximum_capacity_multiple=1.50,
        ),
        "wide_capacity": PrivateAbsorptionRule(
            capacity_increase_fraction_per_100_basis_points=0.10,
            maximum_capacity_multiple=2.00,
        ),
    }
    absorption_paths = []
    absorption_summaries = []
    for name, result in results.items():
        for capacity_name, absorption_rule in absorption_rules.items():
            diagnostics = build_private_absorption_diagnostics(result, absorption_rule)
            absorption_paths.append(
                diagnostics.assign(scenario=name, capacity_scenario=capacity_name)
            )
            absorption_summaries.append(
                {
                    "scenario": name,
                    "capacity_scenario": capacity_name,
                    **summarize_private_absorption(diagnostics),
                }
            )
    pd.concat(absorption_paths, ignore_index=True).to_csv(
        OUTPUT_DIR / "sequential_crisis_2026_private_absorption_paths.csv",
        index=False,
    )
    pd.DataFrame(absorption_summaries).to_csv(
        OUTPUT_DIR / "sequential_crisis_2026_private_absorption_summary.csv",
        index=False,
    )

    config = {
        "experiment": "Sequential rate-interest-income-inflation feedback",
        "start": str(START),
        "end": str(END),
        "treasury_premium_basis_points": PREMIUM_BASIS_POINTS,
        "treasury_premium_quarters": PREMIUM_QUARTERS,
        "private_credit_spread_basis_points": PRIVATE_CREDIT_SPREAD_BASIS_POINTS,
        "private_credit_spread_quarters": PRIVATE_CREDIT_SPREAD_QUARTERS,
        "inflation_ceilings": INFLATION_CEILINGS,
        "sustained_breach_quarters": SUSTAINED_BREACH_QUARTERS,
        "terminal_debt_target_imposed": False,
        "policy_rule": asdict(policy_rule),
        "feedback_rule": asdict(feedback_rule),
        "interest_income_rules": {
            name: asdict(parameters["income"]) for name, parameters in scenarios.items()
        },
        "interest_recipient_share_calibration": str(HOLDER_CALIBRATION_PATH),
        "private_absorption_rules": {name: asdict(rule) for name, rule in absorption_rules.items()},
        "warnings": [
            (
                "Interest-recipient shares approximate official aggregate holdings; "
                "spending fractions remain scenario assumptions."
            ),
            "Endogenous Treasury investor demand and auction clearing remain outside this slice.",
            "Private-absorption outputs are sensitivity diagnostics, not estimated demand curves.",
            "Inflation expectations are represented only through reduced-form persistence.",
            "Reserve interest is recorded elsewhere but has not entered this demand channel.",
            "Ceiling breaches are diagnostics; inflation is not clipped to a ceiling.",
            "Scenario comparisons are conditional and are not crisis probabilities.",
        ],
    }
    (CONFIG_DIR / "sequential_crisis_2026.json").write_text(
        json.dumps(config, indent=2, sort_keys=True) + "\n"
    )
    print(four_percent_summary.to_string(index=False))
    print("Wrote sequential crisis paths, summaries, frontier, and configuration")


if __name__ == "__main__":
    main()
